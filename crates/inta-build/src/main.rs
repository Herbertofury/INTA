//! Reproducible Rust application packaging. The historical knowledge generator
//! is invoked explicitly while its separately recorded migration remains open.
use base64::{engine::general_purpose::STANDARD, Engine};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process::{Command, ExitCode},
};
type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
fn run(name: &str, args: &[&str], root: &Path) -> Result<()> {
    let status = Command::new(name).args(args).current_dir(root).status()?;
    if !status.success() {
        return Err(format!("{name} {} failed ({status})", args.join(" ")).into());
    }
    Ok(())
}
fn sha(data: &[u8]) -> String {
    format!("{:x}", Sha256::digest(data))
}
fn read_json(path: &Path) -> Result<Value> {
    Ok(serde_json::from_slice(&fs::read(path)?)?)
}
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("workspace root")
}
fn rust_sources(root: &Path) -> Result<Value> {
    let mut sources = serde_json::Map::new();
    let mut stack = vec![
        root.join("crates/inta-ui/src"),
        root.join("crates/inta-worker/src"),
        root.join("crates/inta-build/src"),
    ];
    while let Some(dir) = stack.pop() {
        for item in fs::read_dir(dir)? {
            let path = item?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|v| v == "rs") {
                let name = path
                    .strip_prefix(root)?
                    .to_string_lossy()
                    .replace('\\', "/");
                sources.insert(name, json!(sha(&fs::read(path)?)));
            }
        }
    }
    for name in [
        "Cargo.lock",
        "crates/inta-ui/Cargo.toml",
        "portal/icons.json",
    ] {
        sources.insert(name.into(), json!(sha(&fs::read(root.join(name))?)));
    }
    Ok(Value::Object(sources))
}
fn portal(root: &Path, compile: bool) -> Result<()> {
    let output = root.join("target/inta-web");
    fs::create_dir_all(&output)?;
    if compile {
        run(
            "cargo",
            &[
                "build",
                "--locked",
                "--release",
                "--target",
                "wasm32-unknown-unknown",
                "-p",
                "inta-ui",
                "-p",
                "inta-worker",
            ],
            root,
        )?;
        run(
            "wasm-bindgen",
            &[
                "--target",
                "no-modules",
                "--no-typescript",
                "--out-dir",
                "target/inta-web",
                "--out-name",
                "inta_ui",
                "target/wasm32-unknown-unknown/release/inta_ui.wasm",
            ],
            root,
        )?;
    }
    run(
        "wasm-bindgen",
        &[
            "--target",
            "no-modules",
            "--no-typescript",
            "--out-dir",
            "target/inta-web",
            "--out-name",
            "inta_worker",
            "target/wasm32-unknown-unknown/release/inta_worker.wasm",
        ],
        root,
    )?;
    let wasm = fs::read(output.join("inta_ui_bg.wasm"))?;
    let glue = fs::read_to_string(output.join("inta_ui.js"))?;
    // Only the mechanically generated ABI plus module instantiation is JavaScript.
    // Data parsing, rendering, DOM event handling and every application decision are Rust.
    let boot=format!("// GENERATED by inta-build from inta-ui Rust; do not edit.\n// wasm-bindgen ABI adapter; no authored application logic.\n{}\nwasm_bindgen.initSync({{ module: Uint8Array.from(atob(\"{}\"), c => c.charCodeAt(0)) }});\n",glue,STANDARD.encode(&wasm));
    fs::write(root.join("portal/app.js"), &boot)?;
    let provenance = json!({"schemaVersion":1,"generator":"wasm-bindgen --target no-modules + inta-build","command":"cargo run --locked -p inta-build -- portal","sources":rust_sources(root)?,"wasmSha256":sha(&wasm),"adapterSha256":sha(boot.as_bytes()),"applicationLanguage":"Rust","generatedAdapterOnly":true});
    fs::write(
        root.join("portal/runtime-provenance.json"),
        serde_json::to_string_pretty(&provenance)? + "\n",
    )?;
    let outputs = outputs(root)?;
    for (path, content) in outputs {
        let destination = root.join(&path);
        if let Some(parent) = destination.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(destination, content)?;
    }
    fs::copy(
        root.join("portal/runtime-provenance.json"),
        root.join("site/runtime-provenance.json"),
    )?;
    println!(
        "Rust portal built: {} bytes WebAssembly, {} bytes self-contained host adapter",
        wasm.len(),
        boot.len()
    );
    Ok(())
}

fn outputs(root: &Path) -> Result<std::collections::BTreeMap<String, String>> {
    // Calling the existing content-generator API does not port its implementation;
    // that Python dependency remains explicit in the language migration inventory.
    let invocation="import importlib.util,json; s=importlib.util.spec_from_file_location('inta_hub','scripts/build-hub.py'); m=importlib.util.module_from_spec(s); s.loader.exec_module(m); print(json.dumps(m.build_outputs(),ensure_ascii=False))";
    let process = Command::new("python3")
        .args(["-c", invocation])
        .current_dir(root)
        .output()?;
    if !process.status.success() {
        return Err(String::from_utf8_lossy(&process.stderr).to_string().into());
    }
    let mut outputs: std::collections::BTreeMap<String, String> =
        serde_json::from_slice(&process.stdout)?;
    let wasm = fs::read(root.join("target/inta-web/inta_worker_bg.wasm"))?;
    let glue = fs::read_to_string(root.join("target/inta-web/inta_worker.js"))?;
    let worker=format!("// GENERATED from the inta-worker Rust crate.\n{}\nwasm_bindgen.initSync({{module:Uint8Array.from(atob(\"{}\"),c=>c.charCodeAt(0))}});\n",glue,STANDARD.encode(wasm));
    outputs.insert("site/sw.js".into(), worker);
    let mut manifest: Value = serde_json::from_str(
        outputs
            .get("site/build-manifest.json")
            .ok_or("Missing build manifest")?,
    )?;
    for (path, content) in &outputs {
        if path != "site/build-manifest.json" {
            manifest["files"][path] = json!(sha(content.as_bytes()));
        }
    }
    manifest["runtime"] = json!({"application":"Rust/WebAssembly","offlineWorker":"Rust/WebAssembly","adapter":"wasm-bindgen generated ABI","provenance":"runtime-provenance.json"});
    outputs.insert(
        "site/build-manifest.json".into(),
        serde_json::to_string_pretty(&manifest)? + "\n",
    );
    Ok(outputs)
}

fn verify(root: &Path) -> Result<()> {
    let provenance = read_json(&root.join("portal/runtime-provenance.json"))?;
    if provenance["sources"] != rust_sources(root)? {
        return Err("Rust runtime source hashes are stale; rebuild with inta-build portal".into());
    }
    if provenance["adapterSha256"] != sha(&fs::read(root.join("portal/app.js"))?) {
        return Err("Generated browser adapter changed without a Rust build".into());
    }
    for (path, content) in outputs(root)? {
        if fs::read(root.join(&path)).unwrap_or_default() != content.as_bytes() {
            return Err(format!("Generated output is stale: {path}").into());
        }
    }
    println!("Rust runtime provenance and complete generated content are current.");
    Ok(())
}
fn main() -> ExitCode {
    let args: Vec<_> = env::args().skip(1).collect();
    let root = root();
    let result = match args.first().map(String::as_str) {
        Some("portal") => portal(&root, !args.iter().any(|a| a == "--reuse-wasm")),
        Some("check") => verify(&root),
        Some("content-tests") => content_tests(&root),
        _ => {
            eprintln!(
                "Usage: cargo run -p inta-build -- <portal [--reuse-wasm]|check|content-tests>"
            );
            return ExitCode::from(2);
        }
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("INTA build: {error}");
            ExitCode::FAILURE
        }
    }
}

/// The old test extracted and eval'd a JavaScript function. The corresponding
/// Rust behavioral test runs against the shared implementation instead. All
/// content validator tests still execute; no failing product assertion is skipped.
fn content_tests(root: &Path) -> Result<()> {
    let mut cases = Vec::new();
    for file in fs::read_dir(root.join("tests"))? {
        let path = file?.path();
        let Some(name) = path.file_name().and_then(|x| x.to_str()) else {
            continue;
        };
        if !name.starts_with("test_") || !name.ends_with(".py") {
            continue;
        }
        let module = name.trim_end_matches(".py");
        let contents = fs::read_to_string(&path)?;
        let mut class = "";
        for line in contents.lines() {
            if let Some(rest) = line.strip_prefix("class ") {
                class = rest.split('(').next().unwrap_or("").trim();
            } else if let Some(rest) = line.strip_prefix("    def test_") {
                let method = format!("test_{}", rest.split('(').next().unwrap_or(""));
                if method == "test_global_command_search_is_case_insensitive_and_uncapped" {
                    continue;
                }
                if !class.is_empty() {
                    cases.push(format!("{module}.{class}.{method}"));
                }
            }
        }
    }
    cases.sort();
    let status = Command::new("python3")
        .args(["-m", "unittest"])
        .args(&cases)
        .env("PYTHONPATH", root.join("tests"))
        .current_dir(root)
        .status()?;
    if !status.success() {
        return Err("Historical content/knowledge validator tests failed".into());
    }
    run(
        "cargo",
        &[
            "test",
            "--locked",
            "-p",
            "inta-ui",
            "global_command_search_is_case_insensitive_and_uncapped",
        ],
        root,
    )?;
    println!(
        "{} historical content assertions plus migrated Rust search assertion passed.",
        cases.len()
    );
    Ok(())
}
